/*
  НАСТРОЙКИ VITE

  Vite — это "сборщик". Аналогия: ты пишешь книгу в 30 отдельных черновиках
  (файлы .tsx, .css), а Vite — типография, которая собирает из них одну
  аккуратную книгу (папку dist/), понятную любому браузеру.
  А в режиме разработки (npm run dev) Vite мгновенно показывает изменения,
  как только ты сохранил файл.
*/
import { defineConfig } from 'vite'
import react from '@vitejs/plugin-react'

export default defineConfig({
  // Плагин, который учит Vite понимать React-разметку (JSX/TSX).
  plugins: [react()],

  // base: './' — все пути к файлам делаем ОТНОСИТЕЛЬНЫМИ.
  // Зачем: GitHub Pages открывает сайт по адресу вида
  //   https://ИМЯ.github.io/НАЗВАНИЕ-РЕПОЗИТОРИЯ/
  // Если бы пути были абсолютные ("/assets/app.js"), браузер искал бы
  // файлы в https://ИМЯ.github.io/assets/... — а там пусто.
  // С './' он ищет "рядом с собой" — работает при любом адресе.
  base: './',
})
